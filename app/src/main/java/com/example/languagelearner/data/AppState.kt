package com.example.languagelearner.data

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.firestore.FirebaseFirestore

data class SpeakingPrompt(
    val situationTitle: String,
    val situationContext: String,
    val partnerSays: String,          // What the AI partner says to you
    val yourTask: String,              // What you need to answer in your own words
    val helpfulVocabulary: List<String>,// Vocabulary hints
    val nativeExample: String,         // Natural native answer
    val languageCode: String
)

data class WordEvaluation(
    val word: String,
    val isCorrect: Boolean
)

data class PracticeRecord(
    val id: String = "",
    val languageName: String = "",
    val situationTitle: String = "",
    val levelTitle: String = "",
    val fluencyScore: Int = 0,
    val spokenText: String = "",
    val grammarFeedback: String = "",
    val nativeSuggestion: String = "",
    val timestamp: Long = System.currentTimeMillis()
)

object AppState {
    var selectedLanguageName by mutableStateOf("English")
    var selectedLanguageCode by mutableStateOf("en")
    var selectedLanguageFlag by mutableStateOf("🇬🇧")

    var selectedLevelTitle by mutableStateOf("Beginner")
    var selectedLevelBadge by mutableStateOf("A1 - A2")

    var selectedSituationTitle by mutableStateOf("Meeting People & Small Talk")
    var selectedSituationEmoji by mutableStateOf("🤝")

    // The dynamic prompt generated by Gemini AI
    var activePrompt by mutableStateOf<SpeakingPrompt?>(null)
    var isGeneratingPrompt by mutableStateOf(false)
    var isEvaluatingSpeech by mutableStateOf(false)

    // Real evaluation results
    var lastRecognizedSpeech by mutableStateOf("")
    var lastAccuracyScore by mutableStateOf(0)
    var lastWordEvaluations by mutableStateOf<List<WordEvaluation>>(emptyList())
    var lastAiTip by mutableStateOf("")
    var lastGrammarFeedback by mutableStateOf("")
    var lastNativeSuggestion by mutableStateOf("")

    // Speech recognition locale mapping
    fun getSpeechLocale(): String {
        return when (selectedLanguageCode) {
            "es" -> "es-ES"
            "fr" -> "fr-FR"
            "de" -> "de-DE"
            "it" -> "it-IT"
            "ja" -> "ja-JP"
            "ko" -> "ko-KR"
            "hi" -> "hi-IN"
            "pa" -> "pa-IN" // Punjabi
            "zh" -> "zh-CN"
            "pt" -> "pt-BR"
            "ru" -> "ru-RU"
            else -> "en-US"
        }
    }

    // Updates AppState with real Gemini AI evaluation results
    fun updateEvaluation(result: GeminiEvaluationResult, spokenText: String) {
        lastRecognizedSpeech = spokenText
        lastAccuracyScore = result.fluencyScore
        lastGrammarFeedback = result.grammarFeedback
        lastAiTip = result.aiTip
        lastNativeSuggestion = result.nativeSuggestion
        lastWordEvaluations = spokenText.trim().split(Regex("\\s+")).filter { it.isNotBlank() }.map {
            WordEvaluation(word = it, isCorrect = true)
        }
    }

    // Saves the current speaking practice session to Firestore
    fun saveProgressToFirestore(onComplete: ((Boolean) -> Unit)? = null) {
        val currentUser = FirebaseAuth.getInstance().currentUser
        val userId = currentUser?.uid ?: "guest_user"

        val record = hashMapOf(
            "userId" to userId,
            "languageName" to selectedLanguageName,
            "situationTitle" to selectedSituationTitle,
            "levelTitle" to selectedLevelTitle,
            "fluencyScore" to lastAccuracyScore,
            "spokenText" to lastRecognizedSpeech,
            "grammarFeedback" to lastGrammarFeedback,
            "nativeSuggestion" to lastNativeSuggestion,
            "timestamp" to System.currentTimeMillis()
        )

        FirebaseFirestore.getInstance()
            .collection("users")
            .document(userId)
            .collection("practice_records")
            .add(record)
            .addOnSuccessListener {
                onComplete?.invoke(true)
            }
            .addOnFailureListener {
                onComplete?.invoke(false)
            }
    }

    // Returns the AI-generated prompt or a reliable instant fallback
    fun getCurrentPrompt(): SpeakingPrompt {
        return activePrompt ?: SpeakingPrompt(
            situationTitle = selectedSituationTitle,
            situationContext = "Roleplay conversation in $selectedLanguageName.",
            partnerSays = "Hello! Nice to meet you today.",
            yourTask = "Respond freely in $selectedLanguageName for this situation.",
            helpfulVocabulary = listOf("hello", "please", "thank you"),
            nativeExample = "Hello! I am glad to speak with you.",
            languageCode = getSpeechLocale()
        )
    }

    // Instant offline fallback evaluator (used if network is unavailable)
    fun evaluateSpeech(spokenText: String) {
        lastRecognizedSpeech = spokenText
        val words = spokenText.trim().split(Regex("\\s+")).filter { it.isNotBlank() }
        val wordCount = words.size

        val fluencyScore = when {
            wordCount == 0 || spokenText.contains("Tap the microphone") -> 0
            wordCount in 1..2 -> 35
            wordCount in 3..5 -> 65
            wordCount in 6..9 -> 85
            else -> 95
        }
        lastAccuracyScore = fluencyScore

        lastWordEvaluations = words.map { word ->
            WordEvaluation(word = word, isCorrect = true)
        }

        lastAiTip = when {
            wordCount == 0 -> "We didn't catch your voice. Tap the microphone and speak your response out loud!"
            wordCount in 1..2 -> "You spoke just a couple words. Try answering with a full sentence to sound more fluent."
            wordCount in 3..5 -> "Good start! You gave a clear answer. Adding details will make it sound even more natural."
            else -> "Fantastic conversational fluency! You constructed a complete sentence that directly responds to the situation."
        }

        lastGrammarFeedback = if (wordCount >= 3) {
            "Sentence structure is clear and responsive to the scenario."
        } else {
            "Try expanding your response into a complete sentence."
        }

        lastNativeSuggestion = getCurrentPrompt().nativeExample
    }
}